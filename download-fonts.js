import fs from 'fs';
import https from 'https';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const fonts = [
  {
    name: 'NotoSansRegular',
    url: 'https://github.com/notofonts/noto-fonts/raw/main/hinted/ttf/NotoSans/NotoSans-Regular.ttf'
  },
  {
    name: 'NotoSansBold',
    url: 'https://github.com/notofonts/noto-fonts/raw/main/hinted/ttf/NotoSans/NotoSans-Bold.ttf'
  }
];

function downloadFile(url) {
  return new Promise((resolve, reject) => {
    function get(currentUrl) {
      https.get(currentUrl, (res) => {
        if (res.statusCode === 301 || res.statusCode === 302) {
          get(res.headers.location);
          return;
        }
        if (res.statusCode !== 200) {
          reject(new Error(`Failed to get URL ${currentUrl}: ${res.statusCode}`));
          return;
        }
        const data = [];
        res.on('data', (chunk) => data.push(chunk));
        res.on('end', () => resolve(Buffer.concat(data)));
        res.on('error', reject);
      }).on('error', reject);
    }
    get(url);
  });
}

async function main() {
  console.log('Downloading fonts...');
  try {
    const results = {};
    for (const font of fonts) {
      console.log(`Downloading ${font.name} from ${font.url}...`);
      const buffer = await downloadFile(font.url);
      console.log(`Downloaded ${font.name}, size: ${buffer.length} bytes`);
      results[font.name] = buffer.toString('base64');
    }

    const outputContent = `// This file is auto-generated by download-fonts.js. Do not edit manually.
export const NotoSansRegular = '${results.NotoSansRegular}';
export const NotoSansBold = '${results.NotoSansBold}';
`;

    const outputPath = path.join(__dirname, 'src', 'utils', 'fonts.ts');
    fs.writeFileSync(outputPath, outputContent, 'utf-8');
    console.log(`Successfully generated fonts file at ${outputPath}`);
  } catch (error) {
    console.error('Error downloading fonts:', error);
    process.exit(1);
  }
}

main();
